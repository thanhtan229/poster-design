module.exports = async function (context) {
  const { page, pause, assert, selectRegion, state, openMenu, command, openLayerMenu, openBlankLayerMenu } = context
  const historyState = () => page.evaluate(() => {
    const h = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('historyStore')
    return { pointer: h.dHistoryParams.stackPointer, count: h.dHistoryStack.changes.length }
  })
  async function reset(group = false) {
    if (await page.$('[data-feedback-close]')) await page.click('[data-feedback-close]')
    await page.evaluate(group => {
      testReset(group)
      const h = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('historyStore')
      h.dHistoryStack.changes = []
      h.dHistoryStack.inverseChanges = []
      h.dHistoryParams.stackPointer = -1
    }, group)
    await pause(250)
  }
  const layerMenu = uuid => uuid ? openLayerMenu(uuid) : openBlankLayerMenu()
  const notice = () => page.$eval('[data-feedback-message]', el => el.textContent.trim())
  async function quickUndo() {
    await page.waitForSelector('[data-feedback-undo]', { visible: true })
    await page.click('[data-feedback-undo]')
    await pause(250)
    assert.equal(await notice(), 'Đã hoàn tác')
  }
  const redo = async () => {
    await page.keyboard.down('Control'); await page.keyboard.down('Shift')
    await page.keyboard.press('z')
    await page.keyboard.up('Shift'); await page.keyboard.up('Control')
    await pause(250)
  }
  await page.click('#style-panel .style-tab .tab:nth-child(2)')
  await reset()
  await layerMenu()
  await command('Ẩn tất cả')
  assert.equal(await notice(), 'Đã ẩn 4 phần tử')
  assert.equal((await historyState()).pointer, 0, 'A bulk menu command creates exactly one history entry')
  await quickUndo()
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 0)
  assert.equal((await historyState()).pointer, -1)
  await redo()
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 4, 'Redo still works after quick undo')
  await layerMenu('a')
  await command('Hiện tất cả')
  assert.equal(await notice(), 'Đã hiện 4 phần tử')
  await quickUndo()
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 4)
  await reset()
  await layerMenu()
  await page.click('#menu-bg [data-action="hide-all"]')
  await page.waitForSelector('[data-feedback-undo]', { visible: true })
  await page.click('[data-feedback-undo]')
  await pause(450)
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 0, 'Immediate quick undo works without waiting for mouse history debounce')
  assert.deepEqual(await historyState(), { pointer: -1, count: 1 }, 'No delayed duplicate history entry appears after immediate undo')
  await reset()
  await layerMenu()
  await command('Ẩn tất cả')
  await layerMenu('a')
  await quickUndo()
  assert.equal(await page.$eval('#menu-bg', el => getComputedStyle(el).display), 'none', 'Quick undo closes a context menu that was opened afterward')
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 0)
  await reset()
  await layerMenu()
  await command('Ẩn tất cả')
  await page.keyboard.down('Control'); await page.keyboard.press('z'); await page.keyboard.up('Control')
  await pause(250)
  assert.equal(await page.$('[data-action-feedback]'), null, 'Keyboard undo dismisses the old quick-undo notification')
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 0)
  await reset(true)
  await page.evaluate(() => {
    testStore.dWidgets.find(w => w.uuid === 'child1').lock = true
    testStore.dWidgets.find(w => w.uuid === 'g2').hidden = true
  })
  await layerMenu()
  await command('Khóa tất cả')
  assert.equal(await notice(), 'Đã khóa 5 phần tử', 'Counts omit layers that already had the requested state')
  await quickUndo()
  assert.deepEqual(await page.evaluate(() => testStore.dWidgets.filter(w => w.lock).map(w => w.uuid)), ['child1'])
  assert.equal(await page.evaluate(() => testStore.dWidgets.find(w => w.uuid === 'g2').hidden), true)
  await layerMenu()
  await command('Mở khóa tất cả')
  assert.equal(await notice(), 'Đã mở khóa 1 phần tử')
  await quickUndo()
  await reset(true)
  const original = (await state()).widgets
  await layerMenu()
  await command('Xóa tất cả')
  assert.equal(await notice(), 'Đã xóa 6 phần tử')
  assert.deepEqual((await state()).widgets, [])
  await quickUndo()
  assert.deepEqual((await state()).widgets, original, 'Quick undo restores all groups, children and layer order')
  await redo()
  assert.deepEqual((await state()).widgets, [])
  await reset()
  await selectRegion()
  await openMenu()
  await command('Ẩn')
  assert.equal(await notice(), 'Đã ẩn 2 phần tử')
  await quickUndo()
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 0)
  await selectRegion()
  await openMenu()
  await command('Nhân bản')
  assert.equal(await notice(), 'Đã nhân bản 2 phần tử')
  assert.equal((await state()).widgets.length, 6)
  await quickUndo()
  assert.equal((await state()).widgets.length, 4)
  await reset()
  await selectRegion()
  await openMenu()
  await command('Nhóm')
  assert.equal(await notice(), 'Đã gom nhóm 2 phần tử')
  await quickUndo()
  assert.deepEqual((await state()).widgets.map(w => w.uuid), ['bg', 'a', 'b', 'c'])
  await reset()
  await page.evaluate(() => testStore.dWidgets.find(w => w.uuid === 'b').top = 200)
  await selectRegion()
  // Select both unequal-position layers using the model, then exercise the actual menu.
  await page.evaluate(() => { testStore.dSelectWidgets = testStore.dWidgets.filter(w => ['a', 'b'].includes(w.uuid)); testStore.dActiveElement = testCanvas.dPage; testForce.setUpdateSelect() })
  await pause(450)
  await openMenu()
  await command('Căn trên')
  assert.equal(await notice(), 'Đã căn chỉnh 2 phần tử')
  await quickUndo()
  assert.equal(await page.evaluate(() => testStore.dWidgets.find(w => w.uuid === 'b').top), 200)
  await reset()
  await page.evaluate(() => {
    testStore.dWidgets.find(w => w.uuid === 'c').left = 500
    testStore.dSelectWidgets = testStore.dWidgets.filter(w => ['a', 'b', 'c'].includes(w.uuid))
    testStore.dActiveElement = testCanvas.dPage
    testForce.setUpdateSelect()
  })
  await pause(450)
  await openMenu()
  await command('Theo chiều ngang')
  assert.equal(await notice(), 'Đã phân bố đều 3 phần tử', 'Distribution reports participating elements, including its two anchors')
  await quickUndo()
  assert.equal(await page.evaluate(() => testStore.dWidgets.find(w => w.uuid === 'b').left), 240)
  await reset()
  await selectRegion()
  await openMenu()
  await command('Căn trên')
  assert.equal(await page.$('[data-action-feedback]'), null, 'No-op commands do not show feedback')
  assert.equal((await historyState()).pointer, -1, 'No-op commands do not add history entries')
  await reset()
  await layerMenu()
  await command('Chọn tất cả')
  assert.equal(await notice(), 'Đã chọn 4 phần tử')
  assert.equal((await historyState()).pointer, -1, 'Selection feedback does not pollute edit history')
  await quickUndo()
  assert.deepEqual((await state()).selected, [])
  await selectRegion()
  await layerMenu()
  await command('Bỏ chọn tất cả')
  assert.equal(await notice(), 'Đã bỏ chọn 2 phần tử')
  await quickUndo()
  assert.deepEqual((await state()).selected, ['a', 'b'])
  await layerMenu()
  await command('Đảo ngược lựa chọn')
  assert.equal(await notice(), 'Đã đảo lựa chọn 4 phần tử')
  await quickUndo()
  assert.deepEqual((await state()).selected, ['a', 'b'])
  await reset()
  await layerMenu()
  await command('Khóa tất cả')
  assert.equal(await notice(), 'Đã khóa 4 phần tử')
  await layerMenu('a')
  await command('Ẩn tất cả')
  assert.equal(await page.$$('[data-action-feedback]').then(els => els.length), 1, 'Only the latest notification remains')
  assert.equal(await notice(), 'Đã ẩn 4 phần tử')
  await quickUndo()
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 0)
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.lock).length), 4, 'Quick undo targets the latest operation only')
  await reset()
  await layerMenu()
  await command('Ẩn tất cả')
  await page.evaluate(() => testStore.updateWidgetData({ uuid: 'a', key: 'left', value: 110 }))
  await pause()
  assert.equal(await page.$('[data-action-feedback]'), null, 'A later edit invalidates a stale quick-undo button immediately')
  await reset()
  await layerMenu()
  await command('Chọn tất cả')
  await page.evaluate(() => { testStore.dSelectWidgets = []; testStore.dActiveElement = testStore.dWidgets.find(w => w.uuid === 'a') })
  await pause()
  assert.equal(await page.$('[data-action-feedback]'), null, 'A later selection invalidates selection undo')
  await reset()
  await layerMenu()
  await command('Ẩn tất cả')
  await page.evaluate(() => {
    if (!testStore.dLayouts[1]) testStore.dLayouts.push({ global: { ...testCanvas.dPage }, layers: [] })
    testCanvas.dCurrentPage = 1
  })
  await pause()
  assert.equal(await page.$('[data-action-feedback]'), null, 'Switching pages invalidates feedback')
  await page.evaluate(() => { testCanvas.dCurrentPage = 0 })
  await reset()
  await layerMenu()
  await command('Ẩn tất cả')
  await page.hover('[data-action-feedback]')
  await pause(8500)
  assert(await page.$('[data-feedback-undo]'), 'Hover keeps the undo action available')
  await page.mouse.move(10, 10)
  await page.click('[data-feedback-close]')
  assert.equal(await page.$('[data-action-feedback]'), null, 'Dismiss closes the notification without undoing')
  assert.equal(await page.evaluate(() => testStore.dWidgets.filter(w => w.hidden).length), 4)
  await layerMenu('a')
  await command('Hiện tất cả')
  await page.mouse.move(10, 10)
  await pause(8300)
  assert.equal(await page.$('[data-action-feedback]'), null, 'Notifications expire automatically')
  await layerMenu()
  await command('Xóa tất cả')
  await page.screenshot({ path: '.runtime/action-feedback.png' })
}
