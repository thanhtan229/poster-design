module.exports = async function ({ page, pause, assert, state, selectRegion, openMenu, openBlankLayerMenu, prepareLayers }) {
  await prepareLayers()
  const focus = () => page.evaluate(() => document.activeElement?.getAttribute('data-action') || document.activeElement?.getAttribute('role'))
  async function press(key, expected) {
    await page.keyboard.press(key)
    await pause(35)
    if (expected) assert.equal(await focus(), expected, `${key} focuses ${expected}`)
  }
  async function go(action) {
    for (let i = 0; i < 25; i++) {
      if (await focus() === action) return
      await press('ArrowDown')
    }
    assert.fail(`Could not reach ${action} using ArrowDown`)
  }
  const closed = async () => assert.equal(await page.$eval('#menu-bg', el => getComputedStyle(el).display), 'none')
  await selectRegion()
  const original = (await state()).widgets
  await openMenu()
  assert.equal(await focus(), 'menu', 'Opening a context menu focuses its container')
  await press('ArrowLeft', 'menu')
  assert.deepEqual((await state()).widgets, original, 'Left on the initial container cannot reach canvas movement shortcuts')
  await press('ArrowDown', 'copy')
  await press('ArrowDown', 'duplicate')
  await press('ArrowUp', 'copy')
  await press('ArrowUp', 'del')
  await press('Home', 'copy')
  await press('End', 'del')
  await press('ArrowLeft', 'del')
  await press('ArrowRight', 'del')
  assert.deepEqual((await state()).widgets, original, 'Arrow navigation never moves or deletes canvas layers')
  await press('Home', 'copy')
  await press('Enter')
  await closed()
  assert.deepEqual((await state()).copied, ['a', 'b'], 'Enter executes the focused Copy command')
  await openMenu()
  await go('arrange-menu')
  await press('ArrowRight', 'index-up')
  assert.equal(await page.$eval('[data-action="arrange-menu"]', el => el.getAttribute('aria-expanded')), 'true')
  await go('align')
  await press('ArrowRight', 'align-left')
  await press('ArrowDown', 'align-right')
  await press('ArrowLeft', 'align')
  assert.equal(await page.$eval('[data-action="align"]', el => el.getAttribute('aria-expanded')), 'false', 'Left closes the deepest submenu only')
  assert.equal(await page.$eval('[data-action="arrange-menu"]', el => el.getAttribute('aria-expanded')), 'true')
  await press('ArrowLeft', 'arrange-menu')
  assert.equal(await page.$eval('[data-action="arrange-menu"]', el => el.getAttribute('aria-expanded')), 'false')
  await press('Enter', 'index-up')
  await go('align')
  await press('Enter', 'align-left')
  await press('ArrowDown', 'align-right')
  assert.deepEqual((await state()).widgets, original, 'Navigating two submenu levels leaves layer positions unchanged')
  await page.screenshot({ path: '.runtime/menu-keyboard.png' })
  await press('Enter')
  await pause(150)
  await closed()
  assert.deepEqual((await state()).widgets.filter(w => ['a', 'b'].includes(w.uuid)).map(w => w.left), [240, 240], 'Enter executes a nested alignment command')
  await openMenu()
  await go('arrange-menu')
  await press('ArrowRight', 'index-up')
  await press('End', 'align')
  assert.equal(await page.$eval('[data-action="distribute"]', el => el.getAttribute('aria-disabled')), 'true')
  await press('ArrowDown', 'index-up')
  await press('ArrowUp', 'align')
  await page.$eval('[data-action="distribute"]', el => el.focus())
  await press('Enter', 'distribute')
  assert.equal(await page.$eval('[data-action="distribute"]', el => el.getAttribute('aria-expanded')), 'false', 'A disabled branch cannot open even if focused programmatically')
  await press('Escape')
  await closed()
  assert.deepEqual((await state()).selected, [], 'Escape keeps its existing deselect behavior')
  await selectRegion()
  await openBlankLayerMenu()
  await go('selection-menu')
  await press('ArrowRight', 'select-all')
  await press('Enter')
  await pause(150)
  await closed()
  assert.deepEqual((await state()).selected, ['bg', 'a', 'b', 'c'])
  await openBlankLayerMenu()
  await go('selection-menu')
  await press('Enter', 'select-all')
  await press('ArrowDown', 'deselect-all')
  await press('Enter')
  await pause(150)
  await closed()
  assert.deepEqual((await state()).selected, [])
  // Tab dismisses the popup and leaves normal focus navigation available.
  await page.evaluate(() => {
    const button = document.createElement('button')
    button.id = 'menu-focus-origin'
    button.textContent = 'Focus origin'
    Object.assign(button.style, { position: 'fixed', left: '600px', top: '120px' })
    document.body.append(button)
    button.focus()
  })
  await openBlankLayerMenu()
  await press('ArrowDown', 'paste')
  await press('Tab')
  await closed()
  assert.equal(await page.evaluate(() => !!document.activeElement?.closest('#menu-bg')), false)
  await page.$eval('#menu-focus-origin', el => el.remove())
  await openBlankLayerMenu()
  await go('visibility-menu')
  await press('ArrowRight', 'hide-all')
  await press('Enter')
  await pause(150)
  await closed()
  assert.equal(await page.evaluate(() => testStore.dWidgets.every(w => w.hidden)), true)
  await openBlankLayerMenu()
  await go('visibility-menu')
  await press('ArrowRight', 'show-all')
  await press('Enter')
  await pause(150)
  assert.equal(await page.evaluate(() => testStore.dWidgets.every(w => !w.hidden)), true)
  // Hover and keyboard controls work together without losing the submenu.
  await openBlankLayerMenu()
  await page.hover('[data-action="visibility-menu"]')
  await page.click('[data-action="visibility-menu"]')
  await press('ArrowRight', 'hide-all')
  await page.mouse.move(10, 10)
  await press('ArrowLeft', 'visibility-menu')
  await press('Escape')
  await closed()
  await page.evaluate(() => {
    testStore.dSelectWidgets = []
    testStore.dActiveElement = testStore.dWidgets.find(w => w.uuid === 'a')
  })
  await pause()
  await openMenu()
  const singlePosition = (await state()).widgets.find(w => w.uuid === 'a')
  await press('ArrowLeft', 'menu')
  await press('ArrowRight', 'copy')
  await press('ArrowDown')
  assert.deepEqual((await state()).widgets.find(w => w.uuid === 'a'), singlePosition, 'Initial arrow keys also leave a single selected layer in place')
  await press('Escape')
  await closed()
}
