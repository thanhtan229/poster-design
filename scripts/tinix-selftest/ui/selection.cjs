module.exports = async function (context) {
  const { page, pause, assert, selectRegion, state, openMenu, command, openLayerMenu, openBlankLayerMenu, prepareLayers, prepareOtherPage } = context
  const blankPoint = await prepareLayers()
  await prepareOtherPage()
  await page.evaluate(() => testStore.dWidgets.forEach(w => { w.hidden = true }))
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  assert.equal(await page.$eval('#menu-bg [data-action="select-all"]', el => el.getAttribute('aria-disabled')), 'true', 'Select all is disabled when every layer is hidden')
  await page.mouse.click(10, 10)
  await page.evaluate(() => {
    testReset(true)
    testStore.dWidgets.find(w => w.uuid === 'g2').hidden = true
    testStore.dWidgets.find(w => w.uuid === 'c').lock = true
    testStore.dWidgets.find(w => w.uuid === 'child1').lock = true
  })
  await pause()
  const beforeSelectAll = await page.evaluate(() => JSON.stringify(testStore.dWidgets))
  await openLayerMenu('c')
  await page.click('#menu-bg [data-action="select-all"]')
  await pause(100)
  assert.deepEqual((await state()).selected, ['bg', 'g1'], 'Select all includes visible unlocked roots and treats each group as one element')
  assert.equal(await page.evaluate(() => JSON.stringify(testStore.dWidgets)), beforeSelectAll, 'Select all does not alter any layer data')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), '-1')
  assert.equal(await page.$eval('.moveable-area', el => el.getBoundingClientRect().width > 0), true, 'Select all immediately shows a selection frame')
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  await command('Chọn tất cả')
  assert.deepEqual((await state()).selected, ['bg', 'g1'], 'Select all from empty Layers space is repeatable')
  await page.evaluate(() => {
    testReset()
    testStore.dWidgets.find(w => w.uuid === 'bg').hidden = true
    testStore.dWidgets.find(w => w.uuid === 'a').hidden = true
    testStore.dWidgets.find(w => w.uuid === 'b').lock = true
  })
  await pause()
  await openLayerMenu('a')
  await command('Chọn tất cả')
  assert.deepEqual((await state()).selected, [], 'A sole eligible layer uses single selection')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), 'c')
  assert(await page.$('.moveable-control-box .moveable-direction'), 'Single selection keeps resize controls')
  await page.evaluate(() => testReset())
  await pause()
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  await command('Chọn tất cả')
  assert.deepEqual((await state()).selected, ['bg', 'a', 'b', 'c'], 'Every eligible layer on the current page is selected in layer order')
  assert(!(await state()).selected.includes('other-page'), 'Other pages are not included')
  const point = await page.$eval('.design-canvas', el => { const r = el.getBoundingClientRect(); return { x: r.x + 120 * r.width / 800, y: r.y + 120 * r.width / 800 } })
  await page.mouse.move(point.x, point.y)
  await page.mouse.down()
  await page.mouse.move(point.x + 15, point.y + 15, { steps: 5 })
  await page.mouse.up()
  await pause()
  const movedAll = (await state()).widgets
  assert(movedAll.every(w => w.top > (w.uuid === 'bg' ? 0 : 100)), 'The select-all frame moves every selected layer together')
  await openMenu(420, 120)
  assert.equal(await page.$('#menu-bg [data-action="select-all"]'), null, 'Select all is exclusive to the Layers panel')
  await page.mouse.click(10, 10)
  await page.evaluate(() => { testStore.dWidgets.forEach(w => { w.lock = true }); testStore.dSelectWidgets = []; testStore.dActiveElement = testCanvas.dPage })
  await pause()
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  assert.equal(await page.$eval('#menu-bg [data-action="select-all"]', el => el.getAttribute('aria-disabled')), 'true', 'Select all is disabled when every layer is locked')
  await page.click('#menu-bg [data-action="select-all"]')
  assert.notEqual(await page.$eval('#menu-bg', el => getComputedStyle(el).display), 'none')
  await page.mouse.click(10, 10)
  await page.evaluate(() => { testStore.dWidgets = [] })
  await pause()
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  assert.equal(await page.$eval('#menu-bg [data-action="select-all"]', el => el.getAttribute('aria-disabled')), 'true', 'Select all is disabled on an empty page')
  await page.mouse.click(10, 10)
  await page.evaluate(() => testReset())
  await pause()
  await selectRegion()
  const beforeDeselect = await page.evaluate(() => JSON.stringify(testStore.dWidgets))
  await page.evaluate(() => testForce.setUpdateSelect())
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  assert.equal(await page.$eval('#menu-bg [data-action="deselect-all"]', el => el.getAttribute('aria-disabled')), 'false')
  await page.click('#menu-bg [data-action="deselect-all"]')
  await pause(550)
  assert.deepEqual((await state()).selected, [], 'Deselect all clears a multi-selection')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), '-1')
  assert.equal(await page.evaluate(() => testStore.activeMouseEvent), null, 'Deselect all clears pending drag input')
  assert.equal(await page.$$('.widget-selected').then(els => els.length), 0)
  assert.equal(await page.evaluate(() => JSON.stringify(testStore.dWidgets)), beforeDeselect, 'Deselect all preserves layer data')
  assert.equal(await page.$eval('.design-canvas', el => {
    const r = el.getBoundingClientRect()
    return !!document.elementFromPoint(r.x + 120 * r.width / 800, r.y + 120 * r.width / 800)?.closest('.moveable-control-box')
  }), false, 'A pending delayed refresh does not restore the old selection frame')
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  assert.equal(await page.$eval('#menu-bg [data-action="deselect-all"]', el => el.getAttribute('aria-disabled')), 'true', 'Deselect all is disabled when nothing is selected')
  await page.click('#menu-bg [data-action="deselect-all"]')
  assert.notEqual(await page.$eval('#menu-bg', el => getComputedStyle(el).display), 'none')
  await page.mouse.click(10, 10)
  await openLayerMenu('c')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), 'c')
  await command('Bỏ chọn tất cả')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), '-1', 'Deselect all clears a single selection from a layer row')
  await page.evaluate(() => testReset(true))
  await pause()
  await openLayerMenu('g1')
  await command('Bỏ chọn tất cả')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), '-1', 'Deselect all clears a selected group')
  await openMenu(420, 120)
  assert.equal(await page.$('#menu-bg [data-action="deselect-all"]'), null, 'Deselect all is exclusive to the Layers panel')
  await page.mouse.click(10, 10)
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  await command('Chọn tất cả')
  assert.deepEqual((await state()).selected, ['bg', 'g1', 'g2', 'c'], 'Select all still works after deselecting')
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  await command('Bỏ chọn tất cả')
  assert.deepEqual((await state()).selected, [])
  await page.evaluate(() => { testStore.dWidgets = [] })
  await pause()
  await page.mouse.click(blankPoint.x, blankPoint.y, { button: 'right' })
  await page.waitForSelector('#menu-bg', { visible: true })
  assert.equal(await page.$eval('#menu-bg [data-action="deselect-all"]', el => el.getAttribute('aria-disabled')), 'true', 'Deselect all is disabled on an empty page')
  await page.mouse.click(10, 10)
  await page.evaluate(() => testReset())
  await pause()
  const beforeInvert = await page.evaluate(() => JSON.stringify(testStore.dWidgets.map(({ record, ...widget }) => widget)))
  await openBlankLayerMenu()
  await command('Đảo ngược lựa chọn')
  assert.deepEqual((await state()).selected, ['bg', 'a', 'b', 'c'], 'Inverting an empty selection selects every eligible layer')
  await openLayerMenu('a')
  assert.deepEqual((await state()).selected, ['bg', 'a', 'b', 'c'], 'Right clicking a selected Layers row preserves multi-selection')
  await command('Đảo ngược lựa chọn')
  assert.deepEqual((await state()).selected, [], 'Inverting a full selection deselects everything')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), '-1')
  await openLayerMenu('a')
  await command('Đảo ngược lựa chọn')
  assert.deepEqual((await state()).selected, ['bg', 'b', 'c'], 'Invert replaces a single selected layer with its complement')
  await openBlankLayerMenu()
  await command('Đảo ngược lựa chọn')
  assert.deepEqual((await state()).selected, [])
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), 'a', 'Inverting again restores the original single selection')
  assert(await page.$('.moveable-control-box .moveable-direction'), 'An inverted single selection retains resize controls')
  await selectRegion()
  await openLayerMenu('a')
  assert.deepEqual((await state()).selected, ['a', 'b'])
  await command('Đảo ngược lựa chọn')
  assert.deepEqual((await state()).selected, ['bg', 'c'], 'Invert toggles the original multi-selection')
  await openBlankLayerMenu()
  await command('Đảo ngược lựa chọn')
  assert.deepEqual((await state()).selected, ['a', 'b'], 'Applying invert twice restores a multi-selection')
  assert.equal(await page.evaluate(() => JSON.stringify(testStore.dWidgets.map(({ record, ...widget }) => widget))), beforeInvert, 'Invert preserves layer content, geometry and state')
  await page.evaluate(() => {
    testReset(true)
    testStore.dWidgets.find(w => w.uuid === 'bg').hidden = true
    testStore.dWidgets.find(w => w.uuid === 'c').lock = true
    testStore.dActiveElement = testStore.dWidgets.find(w => w.uuid === 'g1')
  })
  await pause()
  await openLayerMenu('g1')
  await command('Đảo ngược lựa chọn')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), 'g2', 'Groups invert as units while hidden and locked roots are skipped')
  assert.deepEqual((await state()).selected, [])
  await openBlankLayerMenu()
  await command('Đảo ngược lựa chọn')
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), 'g1')
  assert.equal(await page.evaluate(() => testStore.dLayouts[1].layers[0].hidden), false, 'Invert does not modify another page')
  await openMenu(420, 120)
  assert.equal(await page.$('#menu-bg [data-action="invert-selection"]'), null, 'Invert is exclusive to the Layers panel')
  await page.mouse.click(10, 10)
  await page.evaluate(() => {
    testStore.dWidgets.forEach(w => { w.lock = true })
    testStore.dSelectWidgets = []
    testStore.dActiveElement = testCanvas.dPage
  })
  await pause()
  await openBlankLayerMenu()
  assert.equal(await page.$eval('#menu-bg [data-action="invert-selection"]', el => el.getAttribute('aria-disabled')), 'true', 'Invert is disabled when nothing is eligible')
  await page.click('#menu-bg [data-action="invert-selection"]')
  assert.notEqual(await page.$eval('#menu-bg', el => getComputedStyle(el).display), 'none')
  await page.mouse.click(10, 10)
  await page.evaluate(() => { testStore.dWidgets = [] })
  await pause()
  await openBlankLayerMenu()
  assert.equal(await page.$eval('#menu-bg [data-action="invert-selection"]', el => el.getAttribute('aria-disabled')), 'true', 'Invert is disabled on an empty page')
  await page.mouse.click(10, 10)
}
