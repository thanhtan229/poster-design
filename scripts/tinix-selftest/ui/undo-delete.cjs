module.exports = async function (context) {
  const { page, pause, assert, state, openMenu, command, openLayerMenu, openBlankLayerMenu, prepareLayers, prepareOtherPage } = context
  const blankPoint = await prepareLayers()
  await prepareOtherPage()
  await page.evaluate(() => {
    testReset(true)
    for (const item of testStore.dWidgets) {
      item.lock = ['g1', 'child2'].includes(item.uuid)
      item.hidden = ['g2', 'child1'].includes(item.uuid)
    }
    testStore.dWidgets.push({ ...testStore.dWidgets.find(w => w.uuid === 'c'), uuid: 'linked-backdrop', linkedPhotoId: 'c' })
    testStore.dSelectWidgets = testStore.dWidgets.filter(w => ['bg', 'c'].includes(w.uuid))
    testForce.setUpdateSelect()
  })
  await pause(550)
  const beforeDeleteAll = await page.evaluate(() => JSON.parse(JSON.stringify(testStore.dWidgets)))
  const pageBeforeDelete = await page.evaluate(() => JSON.stringify(testCanvas.dPage))
  const otherPageBeforeDelete = await page.evaluate(() => JSON.stringify(testStore.dLayouts[1]))
  await openLayerMenu('g1')
  await page.click('#menu-bg [data-action="delete-all"]')
  await pause(550)
  assert.deepEqual((await state()).widgets, [], 'Delete all removes visible, hidden, locked, grouped and linked layers')
  assert.equal(await page.evaluate(() => testStore.dLayouts[testCanvas.dCurrentPage].layers.length), 0, 'The saved page layer list is cleared as well')
  assert.deepEqual((await state()).selected, [])
  assert.equal(await page.evaluate(() => testStore.dActiveElement.uuid), '-1')
  assert.equal(await page.evaluate(() => testStore.activeMouseEvent), null)
  assert.equal(await page.$$('.design-canvas .layer').then(els => els.length), 0, 'Canvas layer elements are removed')
  assert.equal(await page.$$('.widget-list li[data-uuid]').then(els => els.length), 0, 'Layer rows are removed')
  assert.equal(await page.evaluate(() => JSON.stringify(testCanvas.dPage)), pageBeforeDelete, 'Delete all preserves page size, background and settings')
  assert.equal(await page.evaluate(() => JSON.stringify(testStore.dLayouts[1])), otherPageBeforeDelete, 'Delete all does not touch other pages')
  await page.keyboard.down('Control')
  await page.keyboard.press('z')
  await page.keyboard.up('Control')
  await pause(350)
  assert.deepEqual(await page.evaluate(() => JSON.parse(JSON.stringify(testStore.dWidgets))), beforeDeleteAll, 'Undo restores every deleted layer, its states and relationships in one step')
  await page.keyboard.down('Control')
  await page.keyboard.down('Shift')
  await page.keyboard.press('z')
  await page.keyboard.up('Shift')
  await page.keyboard.up('Control')
  await pause(350)
  assert.deepEqual((await state()).widgets, [], 'Delete all can be redone')
  await openBlankLayerMenu()
  assert.equal(await page.$eval('#menu-bg [data-action="delete-all"]', el => el.getAttribute('aria-disabled')), 'true', 'Delete all is disabled on an empty page')
  await page.click('#menu-bg [data-action="delete-all"]')
  assert.notEqual(await page.$eval('#menu-bg', el => getComputedStyle(el).display), 'none')
  await page.mouse.click(10, 10)
  await page.evaluate(() => testReset())
  await pause()
  await openMenu()
  assert.equal(await page.$('#menu-bg [data-action="delete-all"]'), null, 'Delete all is exclusive to the Layers panel')
  await page.mouse.click(10, 10)
  await openBlankLayerMenu()
  await command('Xóa tất cả')
  assert.deepEqual((await state()).widgets, [], 'Delete all also works from empty Layers panel space')
  assert.equal(await page.evaluate(() => JSON.stringify(testStore.dLayouts[1])), otherPageBeforeDelete)
}
