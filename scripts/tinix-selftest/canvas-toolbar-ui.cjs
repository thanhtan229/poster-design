const puppeteer = require('../../service/node_modules/puppeteer')
const { createEditor } = require('./ui/editor.cjs')
async function main() {
  const browser = await puppeteer.launch({ headless: true })
  try {
    const { page, pause, assert, errors } = await createEditor(browser)
    await page.setViewport({ width: 1920, height: 1080 })
    await pause(300)
    const input = '.quick-size .position-size input'
    await page.click('.quick-size .unit-switch button:first-child')
    const old = await page.evaluate(() => ({ width: testCanvas.dPage.width, height: testCanvas.dPage.height }))
    await page.$eval(input, el => el.select())
    await page.keyboard.type('1000')
    assert.equal(await page.evaluate(() => testCanvas.dPage.width), old.width, 'Typing only edits the draft')
    await page.keyboard.press('Escape')
    await pause()
    assert.equal(await page.$eval(input, el => Number(el.value)), old.width, 'Escape resets draft')
    await page.click(input)
    await page.$eval(input, el => el.select())
    await page.keyboard.type('1000')
    await page.keyboard.press('Enter')
    await pause(250)
    assert.equal(await page.evaluate(() => testCanvas.dPage.width), 1000, 'Enter applies')
    await page.click('.canvas-size-toolbar > .el-button')
    await page.waitForSelector('.el-dialog .size-editor', { visible: true })
    await page.keyboard.press('Escape')
    await pause(400)
    await page.keyboard.down('Control'); await page.keyboard.press('z'); await page.keyboard.up('Control')
    await pause(200)
    assert.equal(await page.evaluate(() => testCanvas.dPage.width), old.width, 'One undo restores page')
    assert.equal(await page.$eval(input, el => Number(el.value)), old.width, 'Toolbar follows undo')
    const centers = await page.$$eval('.quick-size .size-actions svg', els => els.map(el => { const r = el.getBoundingClientRect(); return r.y + r.height / 2 }))
    assert.equal(centers[0], centers[1], 'Icons share center line')
    await page.screenshot({ path: '.runtime/canvas-toolbar-wide.png' })
    await page.setViewport({ width: 1100, height: 800 })
    await pause()
    assert.equal(await page.$eval('.quick-size', el => getComputedStyle(el).display), 'none')
    await page.click('.size-summary')
    await page.waitForSelector('.el-dialog .size-editor', { visible: true })
    assert.equal(await page.$('#page-style .size-editor'), null, 'Sidebar size editor removed')
    assert.deepEqual(errors, [])
    console.log('PASS: draft, Enter, Escape, undo sync, aligned icons, library and narrow layout')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
