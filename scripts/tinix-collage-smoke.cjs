// Uses existing local photos; saves one reviewable demo design and exports its actual JPG.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const puppeteer=require('../service/node_modules/puppeteer'),sharp=require('../service/node_modules/sharp')
const DB=require('../service/node_modules/better-sqlite3')
;(async()=>{
 const db=new DB(path.resolve('service/data/poster.db'),{readonly:true})
 const photos=db.prepare('select url from user_images where source=? and width>600 limit 3').all('upload');db.close()
 assert.equal(photos.length,3,'Need three local photo fixtures')
 const base=process.env.TINIX_APP_URL||'http://127.0.0.1:7009'
 const browser=await puppeteer.launch({headless:true})
 try{
  const page=await browser.newPage(),errors=[],external=[]
  page.on('pageerror',e=>errors.push(e.message))
  let cutoutCalls=0
  page.on('request',r=>{if(r.url().includes('/api/tinix/cutout/birefnet'))cutoutCalls++;if(/^https?:/.test(r.url())&&!r.url().startsWith(base))external.push(r.url())})
  await page.setViewport({width:1550,height:1100});await page.goto(base+'/home',{waitUntil:'networkidle2'})
  await page.waitForSelector('#page-design')
  await page.evaluate(()=>{const el=[...document.querySelectorAll('.classify-item')].find(e=>e.textContent.includes('Cắt dán'));el.click()})
  await page.waitForSelector('.collage-panel')
  await page.type('[data-collage-customer]','QA sửa tách nền')
  const files=await page.$$('.collage-panel input[type=file]')
  const local=p=>path.resolve('service',p.url.replace('/static/','static/'))
  await files[0].uploadFile(local(photos[0]));await files[1].uploadFile(local(photos[1]),local(photos[2]))
  const cutoutResponse = page.waitForResponse(r=>r.url().includes('/api/tinix/cutout/birefnet'),{timeout:190000})
  await page.click('.collage-panel .primary')
  const cutout=await cutoutResponse
  assert.equal(cutout.status(),200,'BiRefNet CUDA route must succeed')
  if(cutout.headers()['x-cutout-cache']!=='hit') assert.match(cutout.headers()['x-cutout-gpu'],/3090/)
  await page.waitForSelector('.review-stage canvas',{visible:true})
  const originalMask=await page.$eval('.review-stage canvas',c=>c.toDataURL())
  const box=await page.$eval('.review-stage canvas',c=>{const r=c.getBoundingClientRect(),stage=c.parentElement.getBoundingClientRect(),d=c.getContext('2d').getImageData(0,0,c.width,c.height).data;for(let y=20;y<Math.min(c.height,(stage.bottom-r.top)*c.height/r.height-30);y+=4)for(let x=20;x<c.width-20;x+=4)if(d[(y*c.width+x)*4+3]>245)return {x:r.x+x*r.width/c.width,y:r.y+y*r.height/c.height};throw Error('No visible opaque subject pixel')})
  await page.mouse.move(box.x,box.y);await page.mouse.down();await page.mouse.move(box.x+25,box.y+30,{steps:6});await page.mouse.up()
  assert((await page.$eval('.review-stage canvas',c=>c.toDataURL()))!==originalMask,'Brush must edit alpha')
  await page.evaluate(()=>[...document.querySelectorAll('.review-tools button')].find(b=>b.textContent==='Hoàn tác').click())
  assert.equal(await page.$eval('.review-stage canvas',c=>c.toDataURL()),originalMask,'Undo restores exact alpha')
  await page.select('.review-tools select','#fff')
  assert.equal(await page.$eval('.review-stage',el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)')
  await page.select('.review-tools select','#20242b')
  await page.$eval('.review-tools input[type=number]',el=>{el.value='2';el.dispatchEvent(new Event('input',{bubbles:true}))})
  await page.evaluate(()=>[...document.querySelectorAll('.el-dialog button')].find(b=>b.textContent.includes('Dùng kết quả này')).click())
  await page.waitForSelector('.created-result a',{timeout:180000})
  const customerUrl=await page.$eval('.created-result a',el=>el.href)
  await page.goto(customerUrl,{waitUntil:'networkidle2'});await page.waitForSelector('.w-image')
  await page.evaluate(()=>[...document.querySelectorAll('.classify-item')].find(e=>e.textContent.includes('Cắt dán')).click())
  const data=await page.evaluate(()=>{const s=document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s;return JSON.parse(JSON.stringify({page:s.get('canvasStore').dPage,layers:s.get('widgetStore').dWidgets}))})
  assert.equal(data.page.width,3543);assert.equal(data.page.height,2362);assert.equal(data.page.dpi,300)
  assert.equal(data.page.collage.printWorkflow,'separate-sheets');assert.equal(data.layers.filter(w=>w.slot).length,3)
  assert(data.layers.some(w=>w.name.includes('Chủ thể')&&w.imgUrl.includes('/static/')))
  const subject=data.layers.find(w=>w.cutoutEdit)
  assert.equal(subject.cutoutEdit.mm,2);assert(subject.cutoutBorderUrl);assert.notEqual(subject.imgUrl,subject.cutoutBorderUrl)
  await page.evaluate(()=>[...document.querySelectorAll('.collage-panel button')].find(b=>b.textContent.includes('Sửa chủ thể trên trang')).click())
  await page.waitForSelector('.review-stage canvas',{visible:true})
  await page.$eval('.review-tools input[type=number]',el=>{el.value='0';el.dispatchEvent(new Event('input',{bubbles:true}))})
  await page.evaluate(()=>[...document.querySelectorAll('.el-dialog button')].find(b=>b.textContent.includes('Dùng kết quả này')).click())
  await page.waitForFunction(()=>document.querySelector('.collage-panel [role=status]')?.textContent.includes('Đã cập nhật'))
  assert.equal(cutoutCalls,1,'Changing border and reopening edit must not run BiRefNet again')
  const edited=await page.evaluate(()=>JSON.parse(JSON.stringify(document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('widgetStore').dWidgets.find(w=>w.cutoutEdit))))
  assert.equal(edited.cutoutEdit.mm,0)
  assert.equal(edited.left,subject.left);assert.equal(edited.top,subject.top);assert.equal(edited.width,subject.width)
  const border=await (await fetch(base+edited.cutoutBorderUrl)).arrayBuffer()
  assert.equal((await sharp(Buffer.from(border)).extractChannel(3).stats()).channels[0].max,0,'Zero mm means no white rim')
  const input=await page.$('.top-title input');await input.click({clickCount:3});await input.type('Cat dan - mau thu san xuat')
  await page.screenshot({path:'.runtime/collage-app.png'})
  const responsePromise=page.waitForResponse(r=>r.url().includes('format=jpg'),{timeout:120000})
  await page.evaluate(()=>[...document.querySelectorAll('button')].find(e=>e.textContent.includes('Xuất JPG để in')).click())
  const response=await responsePromise;assert.equal(response.status(),200)
  const jpeg=Buffer.from(await (await fetch(response.url())).arrayBuffer());const meta=await sharp(jpeg).metadata()
  assert.equal(meta.format,'jpeg');assert.equal(meta.width,3543);assert.equal(meta.height,2362);assert.equal(meta.density,300)
  fs.writeFileSync('.runtime/collage-print.jpg',jpeg)
  assert.deepEqual(errors,[])
  assert(!external.some(u=>/openai|generations|huggingface|replicate/.test(u)))
  const id=new URL(response.url()).searchParams.get('id')
  await page.goto(base+'/home?id='+id,{waitUntil:'networkidle2'});await page.waitForSelector('#page-design')
  const count=await page.evaluate(()=>document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('widgetStore').dLayouts.find(p=>p.global.collage)?.layers.length)
  assert.equal(count,data.layers.length)
  await page.evaluate(()=>[...document.querySelectorAll('.classify-item')].find(e=>e.textContent.includes('Cắt dán')).click())
  await page.evaluate(()=>[...document.querySelectorAll('.collage-panel button')].find(b=>b.textContent.includes('Sửa chủ thể trên trang')).click())
  await page.waitForSelector('.review-stage canvas',{visible:true})
  assert.equal(await page.$eval('.review-tools input[type=number]',el=>Number(el.value)),0,'Saved edit settings reopen')
  assert.equal(cutoutCalls,1,'Reopening saved alpha must not trigger inference')
  await new Promise(resolve=>setTimeout(resolve,400))
  await page.screenshot({path:'.runtime/cutout-review.png'})
  for(let i=0;i<5;i++){
   await page.evaluate(()=>[...document.querySelectorAll('.el-dialog button')].find(b=>b.textContent.trim()==='Hủy').click())
   await page.waitForFunction(()=>document.querySelector('.review-stage canvas')?.width===1)
   await page.evaluate(()=>[...document.querySelectorAll('.collage-panel button')].find(b=>b.textContent.includes('Sửa chủ thể trên trang')).click())
   await page.waitForFunction(()=>document.querySelector('.review-stage canvas')?.width>1)
  }
  assert.equal(cutoutCalls,1,'Repeated review open/close must reuse saved alpha')
  console.log(JSON.stringify({pass:true,designId:id,jpeg:meta.width+'x'+meta.height,dpi:meta.density,layers:count,engine:'BiRefNet',gpu:cutout.headers()['x-cutout-gpu'],cache:cutout.headers()['x-cutout-cache']},null,2))
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
